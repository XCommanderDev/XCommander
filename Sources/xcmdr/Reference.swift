import Foundation
import XCommanderCore

/// The website's command reference, written from the keymap the app ships.
///
/// Generated rather than written by hand, for the reason the rest of this tool exists: a
/// reference that drifts from the code is worse than none, because people trust it. Run it
/// after changing `DefaultKeymap.swift`, and commit the page to the website:
///
///     swift run xcmdr reference --snapshot Fixtures/Xcode-27A266.json \
///         -o ../Website/user/pages/02.docs/03.commands/docs.md
///
/// Groups come out in the order the which-key panel shows them. Each command gets its keys,
/// what it does, the Xcode menu item it presses (read from the snapshot, so the path is the
/// one Xcode actually shows), and its id for `config.toml`.
struct ReferencePage {
    let registry: CommandRegistry
    let keymap: Keymap
    let catalogue: MenuCatalogue?
    let xcodeVersion: String?

    func render() -> String {
        var out: [String] = []
        out.append("""
            ---
            title: Command reference
            template: docs
            description: 'Every key XCommander ships with, the Xcode menu item behind it, and the id to use in your configuration.'
            taxonomy:
                category: docs
            ---

            <!-- Generated by `swift run xcmdr reference` from DefaultKeymap.swift. Don't edit by hand: change the keymap and run it again. -->

            Every command XCommander ships with, grouped the way the which-key panel groups them. \
            **Every sequence starts with the leader key**, <kbd>⌥</kbd><kbd>↩</kbd> unless you chose \
            another one, so <kbd>m</kbd> <kbd>m</kbd> below means <kbd>⌥</kbd><kbd>↩</kbd> then \
            <kbd>m</kbd> then <kbd>m</kbd>. An uppercase letter means with Shift.

            The **Xcode menu item** column is what XCommander presses for you\
            \(xcodeVersion.map { " (as it appears in Xcode \($0))" } ?? ""). Commands marked \
            *XCommander* are ones Xcode doesn't have, done by XCommander itself. The **id** is what \
            you write in your [configuration file](../configuration) to bind a command to other keys.

            If a key does nothing, your Xcode may not have that command: the which-key panel only \
            shows the commands your Xcode offers.

            """)

        let top = rows(at: [])
        // Single keys first, the way Doom lists SPC SPC and SPC : before the groups.
        let singles = top.filter { !$0.row.isGroup }
        if !singles.isEmpty {
            out.append("## Straight after the leader\n")
            out.append(table(singles.map { ([$0.key], $0.id!) }))
        }
        for group in top where group.row.isGroup {
            out.append("## \(keyText([group.key])) — \(group.row.title)\n")
            out.append(table(leaves(under: [group.key])))
            // A group inside a group (w W, the macOS window commands) gets its own table.
            for sub in rows(at: [group.key]) where sub.row.isGroup {
                out.append("### \(keyText([group.key, sub.key])) — \(sub.row.title)\n")
                out.append(table(leaves(under: [group.key, sub.key])))
            }
        }

        let unbound = registry.all.filter { keymap.binding(for: $0.id) == nil }
        if !unbound.isEmpty {
            out.append("""
                ## Commands without a default key

                These are in the [command palette](../everyday-use#the-command-palette) \
                (<kbd>⌥</kbd><kbd>↩</kbd> <kbd>:</kbd>), and you can give them keys in your \
                configuration file.

                """)
            out.append("| Command | Xcode menu item | id |\n|---|---|---|")
            for command in unbound {
                out.append("| \(describe(command)) | \(source(command)) | `\(command.id)` |")
            }
            out.append("")
        }
        out.append("*\(registry.count) commands, \(boundCount()) of them with default keys.*\n")
        return out.joined(separator: "\n")
    }

    // MARK: - walking the keymap

    private struct Node {
        let key: KeyEvent
        let row: WhichKeyRow
        let id: String?
    }

    /// One level of the tree, in the which-key panel's order.
    private func rows(at prefix: [KeyEvent]) -> [Node] {
        let level: [KeyEvent: KeymapEntry]
        if prefix.isEmpty {
            level = keymap.children
        } else if case .group(_, let kids)? = keymap.entry(at: prefix) {
            level = kids
        } else {
            return []
        }
        return keymap.rows(at: prefix, in: registry).compactMap { row in
            guard let (key, entry) = level.first(where: { $0.key.display == row.key }) else { return nil }
            if case .command(let id) = entry { return Node(key: key, row: row, id: id) }
            return Node(key: key, row: row, id: nil)
        }
    }

    private func leaves(under prefix: [KeyEvent]) -> [([KeyEvent], String)] {
        rows(at: prefix).compactMap { node in node.id.map { (prefix + [node.key], $0) } }
    }

    private func boundCount() -> Int {
        registry.all.filter { keymap.binding(for: $0.id) != nil }.count
    }

    // MARK: - formatting

    private func table(_ bindings: [([KeyEvent], String)]) -> String {
        var lines = ["| Keys | Command | Xcode menu item | id |", "|---|---|---|---|"]
        for (keys, id) in bindings {
            guard let command = registry.command(id: id) else { continue }
            lines.append("| \(keyText(keys)) | \(describe(command)) | \(source(command)) | `\(id)` |")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    private func keyText(_ keys: [KeyEvent]) -> String {
        keys.map { "<kbd>\(escape($0.display))</kbd>" }.joined(separator: " ")
    }

    /// The longer of the command's two names: "find file in project" over "find file".
    private func describe(_ command: Command) -> String {
        let text = command.searchText.count > command.title.count ? command.searchText : command.title
        return escape(text.prefix(1).uppercased() + text.dropFirst())
    }

    /// Where the command comes from: an Xcode menu path, or XCommander itself.
    private func source(_ command: Command) -> String {
        switch command.action {
        case .menu:
            return menuPath(command) ?? "Xcode menu"
        case .shortcut(let key):
            return "Xcode shortcut \(keyText([key]))"
        case .popupMenu(let ref):
            return "Toolbar: \(escape(ref.button))"
        case .picker:
            return "*XCommander* picker"
        case .pane:
            return "*XCommander* panes"
        case .transform:
            return "*XCommander* text"
        case .focus:
            return "*XCommander* focus"
        case .companion:
            return "*XCommander*"
        }
    }

    private func menuPath(_ command: Command) -> String? {
        guard let ref = command.menuRef, let catalogue else { return nil }
        if case .bound(let entry, _) = catalogue.resolve(ref) {
            return escape(entry.path.map(Self.generic).joined(separator: " › "))
        }
        return nil
    }

    /// Some items carry what's on screen in their title, like `Close “AppDelegate.swift”`.
    /// The reference names the item, not the file that happened to be open.
    private static func generic(_ title: String) -> String {
        guard let open = title.firstIndex(of: "“") else { return title }
        return title[..<open].trimmingCharacters(in: .whitespaces)
    }

    /// Markdown tables split on `|`, and Grav reads `<` as HTML.
    private func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "|", with: "\\|")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
    }
}
